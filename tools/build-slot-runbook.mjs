/* handoff/ONSITE-SLOTS.md, generated from js/slots.js rather than typed beside it.
 *
 * A marketer opens the Dengage panel's Inline Target Selector, searches a word, and picks a query
 * from the list it produces. This document tells them which word to search and which query to
 * pick, for every place on this site a campaign can be dropped.
 *
 * It is generated because the alternative is a table that describes a slot the site removed three
 * commits ago. Run with --check to fail when the committed file and the map disagree.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = 'handoff/ONSITE-SLOTS.md';

const src = await readFile(join(ROOT, 'js/slots.js'), 'utf8');

/* The map is a literal in the module, so it is read as one rather than by executing the file in a
   context with no window and no document. */
const block = src.match(/var SLOTS = \[([\s\S]*?)\n  \];/)?.[1];
if (!block) { console.error('FAIL  js/slots.js has no SLOTS map'); process.exit(1); }

const slots = [];
for (const m of block.matchAll(/\{\s*id:\s*'([^']+)',\s*\n?\s*pages:\s*('\*'|\[[^\]]*\]),\s*\n?\s*where:\s*'([^']*)',\s*\n?\s*moment:\s*'([^']*)'\s*\}/g)) {
  const pages = m[2] === "'*'" ? '*' : [...m[2].matchAll(/'([^']+)'/g)].map((x) => x[1]);
  slots.push({ id: m[1], pages, where: m[3], moment: m[4] });
}
if (slots.length === 0) { console.error('FAIL  no slot rows parsed'); process.exit(1); }

const rows = slots.map((s) => {
  const where = s.pages === '*' ? 'every page' : s.pages.join(', ');
  return `| \`#${s.id}\` | ${where} | ${s.where} | ${s.moment} |`;
}).join('\n');

const doc = `# The on site slots, and how to target them from the panel

Generated from \`js/slots.js\` by \`tools/build-slot-runbook.mjs\`. Do not edit this file: edit the
map and run the tool. \`bash tools/check-all.sh\` fails when the two disagree.

## How a marketer picks one

\`reference/on-site-message\`, Inline Target Selector: the selector "scans all HTML nodes in page
and finds the ones that contains search word on their class or id", lists optimised query
selectors, and reports a target count for each. It prioritises id queries.

So there are two ways in, and both are deliberate.

**Search \`dn_inline\`** and every slot on the page is listed and highlighted, each with a target
count of 1. Pick the one whose id matches the table below.

**Search \`dn-inline-target\`** and the shared class lists every slot at once, target count equal to
the number of slots on that page. Useful for seeing what a page offers before choosing.

The initial search runs five times over five seconds, because nodes can appear after load. Two of
these slots are drawn by \`js/pages.js\` rather than written into the file, so give the selector
that time rather than searching again immediately.

## The slots

${slots.length} of them. Every one is a place a telecom campaign has a reason to be, not a div
scattered for coverage.

| Query to pick | Pages | Where it sits | The moment it is there for |
|---|---|---|---|
${rows}

## Four rules that decide whether a creative works

Carried from Each one is a property of the platform to design with.

1. **Padding 0 and a transparent background**, or the engine draws a white box around the creative
   and the page looks broken.
2. **Namespace every selector under the creative root id.** Inline creatives are not sandboxed, so
   a rule written as \`.title\` restyles the page it landed in.
3. **The panel strips \`<script>\`.** Behaviour lives in \`onclick\`, and the whole file is pasted
   rather than a fragment.
4. **A pinned top bar covers a fixed header.** This site publishes a clearance and accepts the
   bar's own height report over \`postMessage\`, clamped. That is \`js/slots.js\` and it is already
   handled; nothing has to be done in the panel.

## What the site guarantees about these

- Every id is unique on its page, so the optimised query is always a target count of 1. Asserted.
- Every slot exists **even when the page is empty**. An empty basket, an empty checkout, an empty
  order list and a signed out account all still carry theirs. This was found by a check rather than
  by reasoning: all four were missing, and each is a state a campaign has good reason to target.
- A slot that a page stops carrying fails the build rather than the demonstration.
`;

const current = await readFile(join(ROOT, OUT), 'utf8').catch(() => null);

if (process.argv.includes('--check')) {
  if (current === doc) {
    console.log(`pass  ${OUT} matches the slot map  (${slots.length} slots)`);
    process.exit(0);
  }
  console.log(`FAIL  ${OUT} does not match js/slots.js. Run: node tools/build-slot-runbook.mjs`);
  process.exit(1);
}

await writeFile(join(ROOT, OUT), doc);
console.log(`wrote ${OUT}, ${slots.length} slots`);
